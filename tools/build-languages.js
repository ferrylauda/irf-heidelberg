#!/usr/bin/env node
/*
  Builds the Indonesian and German home pages and the sitemap.

    index.html (English, the source)  +  js/i18n.js  ->  id/index.html, de/index.html, sitemap.xml

  Run after every change to index.html or js/i18n.js:   node tools/build-languages.js
  The generated files are committed, so deploying needs no build step.
  Do not edit id/index.html or de/index.html by hand.
*/
const fs = require("fs");
const path = require("path");
const vm = require("vm");

const root = path.join(__dirname, "..");
const BASE = "https://www.irf-heidelberg.org";
const LANGS = {
  en: { path: "/", locale: "en_GB" },
  id: { path: "/id/", locale: "id_ID" },
  de: { path: "/de/", locale: "de_DE" }
};

const read = (file) => fs.readFileSync(path.join(root, file), "utf8").replace(/\r\n/g, "\n");
const source = read("index.html");

const sandbox = { window: {} };
vm.runInNewContext(read("js/i18n.js"), sandbox);
const I18N = sandbox.window.I18N;

const esc = (s) => s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
const escAttr = (s) => esc(s).replace(/"/g, "&quot;");
const unesc = (s) => s.replace(/&lt;/g, "<").replace(/&gt;/g, ">").replace(/&quot;/g, '"').replace(/&amp;/g, "&");

const I18N_ELEMENT = /<([a-z0-9]+)([^>]*?)\sdata-i18n="([^"]+)"([^>]*)>([\s\S]*?)<\/\1>/g;

function setHead(html, lang) {
  const dict = I18N[lang];
  const url = BASE + LANGS[lang].path;

  html = html.replace('<html lang="en" data-static-lang="en">', `<html lang="${lang}" data-static-lang="${lang}">`);
  html = html.replace(/<title>[\s\S]*?<\/title>/, `<title>${esc(dict["seo.title"])}</title>`);
  html = html.replace(/(<meta name="description" content=")[^"]*(")/, `$1${escAttr(dict["seo.description"])}$2`);
  html = html.replace(/(<meta property="og:title" content=")[^"]*(")/, `$1${escAttr("International Reformed Fellowship Heidelberg")}$2`);
  html = html.replace(/(<meta property="og:description" content=")[^"]*(")/, `$1${escAttr(dict["seo.ogDescription"])}$2`);
  html = html.replace(/(<meta property="og:url" content=")[^"]*(")/, `$1${url}$2`);
  html = html.replace(/(<link rel="canonical" href=")[^"]*(")/, `$1${url}$2`);

  const others = Object.keys(LANGS).filter((l) => l !== lang);
  const localeTags = [`<meta property="og:locale" content="${LANGS[lang].locale}">`]
    .concat(others.map((l) => `<meta property="og:locale:alternate" content="${LANGS[l].locale}">`))
    .join("\n  ");
  html = html.replace(/<meta property="og:locale"[^>]*>\n\s*<meta property="og:locale:alternate"[^>]*>\n\s*<meta property="og:locale:alternate"[^>]*>/, localeTags);

  // Structured data
  html = html.replace(/(<script type="application\/ld\+json">)([\s\S]*?)(<\/script>)/, (m, open, body, close) => {
    const data = JSON.parse(body);
    const [org, event] = data["@graph"];
    org.description = dict["seo.orgDescription"];
    event.name = dict["seo.eventName"];
    event.description = dict["seo.eventDescription"];
    event.url = url;
    const json = JSON.stringify(data, null, 2).split("\n").map((l) => "  " + l).join("\n");
    return `${open}\n${json}\n  ${close}`;
  });

  // Active language link
  html = html.replace(/ aria-current="true"/g, "");
  html = html.replace(`data-lang="${lang}">`, `data-lang="${lang}" aria-current="true">`);
  return html;
}

function build(lang) {
  const dict = I18N[lang];
  const fallback = I18N.en;
  let html = setHead(source, lang);

  html = html.replace(I18N_ELEMENT, (m, tag, before, key, after) => {
    const text = dict[key] || fallback[key];
    if (!text) return m;
    return `<${tag}${before} data-i18n="${key}"${after}>${esc(text)}</${tag}>`;
  });

  // The pages live in sub-folders, so make every local link absolute
  html = html.replace(/(href|src)="(css\/|js\/|images\/|favicon\.svg|legal\.html)/g, '$1="/$2');
  html = html.replace("<!doctype html>", "<!doctype html>\n<!-- Generated by tools/build-languages.js from index.html. Do not edit by hand. -->");
  return html;
}

// Warn if the English text in index.html has drifted from js/i18n.js
let drift = 0;
source.replace(I18N_ELEMENT, (m, tag, before, key, after, inner) => {
  const expected = I18N.en[key];
  if (expected && unesc(inner).trim() !== expected.trim()) {
    drift++;
    console.warn(`  note: English text for "${key}" in index.html differs from js/i18n.js`);
  }
  return m;
});

for (const lang of ["id", "de"]) {
  const dir = path.join(root, lang);
  fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(path.join(dir, "index.html"), build(lang), "utf8");
  console.log(`wrote ${lang}/index.html`);
}

const alternates = Object.keys(LANGS)
  .map((l) => `    <xhtml:link rel="alternate" hreflang="${l}" href="${BASE}${LANGS[l].path}"/>`)
  .concat(`    <xhtml:link rel="alternate" hreflang="x-default" href="${BASE}/"/>`)
  .join("\n");
const urls = Object.keys(LANGS)
  .map((l) => `  <url>\n    <loc>${BASE}${LANGS[l].path}</loc>\n${alternates}\n  </url>`)
  .join("\n");
fs.writeFileSync(
  path.join(root, "sitemap.xml"),
  `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:xhtml="http://www.w3.org/1999/xhtml">\n${urls}\n</urlset>\n`,
  "utf8"
);
console.log("wrote sitemap.xml" + (drift ? ` (${drift} English text difference(s) noted above)` : ""));
